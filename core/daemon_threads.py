"""
Фоновые потоки для шагов плана — тонкая обёртка над threading.

ЧЕМ ЭТОТ ФАЙЛ ЗАМЕНИЛ И ПОЧЕМУ ИМЕННО ТАК
========================================

Раньше шаги плана выполнялись в `ThreadPoolExecutor`, и на остановке
исполнитель вызывал `shutdown(wait=False)` с комментарием «зависший
обработчик не должен держать демон при выходе».

Комментарий был неверно, и это была не ошибка формулировки, а ошибка
модели: у `ThreadPoolExecutor` потоки **не** daemon. Действует
`concurrent.futures.thread._python_exit`, который перед завершением
интерпретатора **джойнит** все потоки пула — независимо от того, с
каким значением вызвали `shutdown`. Проверено на этой машине: NOVA AI
с одним зависшим обработчиком живёт дольше 4 секунд после того, как
уже отрапортовал «остановлен», и сам не завершается. Для голосового
ассистента это худший вид поломки — процесс мёртв на словах и жив на
деле, а супервизор считает, что упал, и поднимает вторую копию.

Поэтому здесь нет пула вообще. Есть ровно один поток на шаг, с
`daemon=True`: такой поток интерпретатор не джойнит, и зависший
инструмент не может удержать NOVA AI на выходе.

Цена этого решения — поток Python нельзя убить. `abandon()` поэтому не
«останавливает» шаг, а честно помечает его покинутым: поток дописывает
своё сам, а мы теряем право на его результат. Покинутые потоки считаются,
потому что иначе серия зависаний превратилась бы в бесконечное число
потоков (см. `max_abandoned`).

ГАРАНТИИ ЭТОГО МОДУЛЯ
=====================

1. Поток не удерживает процесс. `daemon=True` — не украшение, а
   требование: см. первый раздел.
2. Поток не удерживает раннер. Обработчик не ждёт потоки; он ждёт
   `Handle`, у которого есть `wait(timeout)`.
3. Результат не теряется молча. `Handle.value` читается только после
   `wait()`, вернувшего `True`, иначе в нём может быть что угодно.
4. Предел не «раздувается». Превышение — явная ошибка
   `RunnerBusy`, а не тихий запуск потока номер девятый.
"""
from __future__ import annotations

import logging
import threading
from dataclasses import dataclass, field
from typing import Any, Callable, Dict, Optional

logger = logging.getLogger(__name__)


class RunnerBusy(RuntimeError):
    """Раннер отказал в новом шаге из-за исчерпания лимита.

    Отдельный тип, а не просто `RuntimeError`, потому что вызывающий
    код обязан отличать «система забита зависшими шагами» (это
    диагноз: инструменты не отвечают) от «раннер сломан» (это уже
    баг). Первое — повод сообщить сэру, что внешние системы не
    отвечают, и остановить задачу; второе — повод поднять тревогу в
    логах.
    """


#: eq=False обязателен: dataclass с eq=True теряет __hash__ и становится
#: непригодным в качестве ключа dict, которым держится учёт потоков.
@dataclass(eq=False)
class Handle:
    """Ручка одного запущенного шага.

    Объект живёт дольше потока, если поток завис: именно поэтому
    «покинут» он или нет, это состояние хендла, а не флаг потока.
    """

    name: str
    #: Сигнал о завершении. Поток ставит его последним действием —
    #: после `value`/`error`, поэтому `wait() == True` всегда означает
    #: «данные готовы», а не «поток куда-то пошёл».
    _done: threading.Event = field(default_factory=threading.Event)

    value: Any = None
    error: Optional[BaseException] = None

    #: Покинут ли шаг. Пока True, поток считается заброшенным: его
    #: результат уже не пригодится вызывающему коду.
    abandoned: bool = False

    #: Жив ли поток. Не из `is_alive()`: у уже завершившегося потока
    #: состояние меняется, и опрос из другого потока без синхронизации
    #: ничего не гарантирует.
    finished: bool = False

    def wait(self, timeout: Optional[float] = None) -> bool:
        """Ждёт завершения шага.

        `False` означает «не успел за timeout» — это НЕ «провалился».
        Провалившийся шаг возвращает `True` и несёт `error`.
        Различать это обязательно: иначе таймаут-шаг невозможно
        отличить от упавшего, а планировщик перепланирует и то и другое.
        """
        return self._done.wait(timeout)

    @property
    def ok(self) -> bool:
        """Завершился ли шаг без исключения."""
        return self._done.is_set() and self.error is None


class DaemonRunner:
    """Пул фоновых потоков для шагов плана.

    Не пул в смысле очереди задач: никакого очерёдного распределения
    здесь нет. Нужен предел на число одновременно живых потоков и
    отдельно — на число покинутых, потому что это разные вещи: поток
    может быть живым и при этом покинутым.
    """

    def __init__(
        self,
        max_active: int = 8,
        max_abandoned: int = 8,
    ) -> None:
        if max_active < 1:
            raise ValueError("max_active должен быть не меньше 1")
        if max_abandoned < 0:
            raise ValueError("max_abandoned не может быть отрицательным")

        self._max_active = max_active
        self._max_abandoned = max_abandoned

        #: Один лок на весь раннер. Потоки короткоживущие, критические
        #: секции короче, а состояние (счётчики, множество потоков)
        #: меняется из двух мест — из вызывающего потока и из
        #: завершившегося. Держать его дороже, чем не держать.
        self._lock = threading.Lock()

        # Живые потоки: хендл → поток. Завершивший удаляет себя сам.
        # Сопоставление по объекту хендла, а не по имени потока:
        # имена шагов повторяются между планами (step_id начинается
        # заново), и поиск по имени рано или поздно нашёл бы чужой
        # поток — то есть помечал бы чужой шаг покинутым.
        self._live: Dict[Handle, threading.Thread] = {}

        #: Сколько потоков сейчас покинуто вызывающим кодом. Уменьшается,
        #: когда поток всё-таки допишет.
        self._abandoned = 0

        #: Раннер остановлен: новые шаги не принимаются. Исходящие
        #: потоки при этом не трогаются — их нечем прервать.
        self._stopped = False

    # ------------------------------------------------------------------
    # Свойства (только чтение — для диагностики и логов)
    # ------------------------------------------------------------------
    @property
    def active(self) -> int:
        """Сколько потоков живёт прямо сейчас."""
        with self._lock:
            return len(self._live)

    @property
    def abandoned(self) -> int:
        """Сколько потоков покинуто и ещё не дописало."""
        with self._lock:
            return self._abandoned

    @property
    def stopped(self) -> bool:
        with self._lock:
            return self._stopped

    # ------------------------------------------------------------------
    # Основное
    # ------------------------------------------------------------------
    def submit(self, fn: Callable[[], Any], *, name: str = "nova_ai-step") -> Handle:
        """Запускает `fn` в фоновом потоке и возвращает ручку.

        Исключение из `fn` НЕ пробрасывается: оно попадает в
        `Handle.error`. Проброс был бы коварством — вызывающий код
        ждёт результата по ручке, а не в `try`, и исключение из
        фонового потока в Python просто печатается в stderr и теряет
        связь с вызвавшим.

        `RunnerBusy` — единственное исключение наружу: это отказ
        запустить, а не результат запуска.
        """
        handle = Handle(name=name)

        with self._lock:
            if self._stopped:
                raise RunnerBusy(
                    "раннер остановлен: новые шаги не принимаются"
                )
            if self._abandoned >= self._max_abandoned:
                # Раньше всего срабатывает этот предел, и это правильно:
                # заброшенный поток — самый вероятный источник новых
                # зависаний. Если исчерпан он, система уже в плохом
                # состоянии, и запускать ещё один шаг значит усугубить.
                raise RunnerBusy(
                    f"слишком много зависших шагов: {self._abandoned} "
                    f"из {self._max_abandoned}. Инструменты не отвечают."
                )
            if len(self._live) >= self._max_active:
                raise RunnerBusy(
                    f"слишком много одновременных шагов: {len(self._live)} "
                    f"из {self._max_active}"
                )
            thread = threading.Thread(
                target=self._run,
                args=(handle, fn),
                name=name,
                daemon=True,  # см. первый раздел: без этого не завершимся
            )
            self._live[handle] = thread

        thread.start()
        return handle

    def abandon(self, handle: Handle) -> None:
        """Помечает шаг покинутым: результат больше не нужен.

        Идемпотентно. Повторный вызов на уже покинутом хендле ничего
        не делает — иначе два независимых места решения «сдаться на
        шаг» (таймаут и отмена) разогнали бы счётчик покинутых вдвое,
        и предел означал бы совсем не то число.
        """
        with self._lock:
            if handle.abandoned:
                return
            handle.abandoned = True
            # Поток мог завершиться между таймаутом и этим вызовом.
            # Тогда он не в _live, и засчитывать его незачем: он уже
            # дописал, проблемы «растущего числа потоков» нет.
            if self._is_live(handle):
                self._abandoned += 1
                logger.warning(
                    "ШАГ ПОКИНУТ | %s | заброшено=%d/%d",
                    handle.name,
                    self._abandoned,
                    self._max_abandoned,
                )
            else:
                logger.info(
                    "ШАГ ПОКИНУТ (уже завершился) | %s",
                    handle.name,
                )

    def stop(self) -> int:
        """Перестаёт принимать новые шаги. Возвращает число живых.

        Исходящие потоки НЕ прерываются, и это не недосмотр, а
        сознательный выбор: поток Python не умеет убивать другой
        поток, а единственный доступный способ — исключение извне —
        оставляет операцию в неопределённом состоянии (файл записан
        наполовину, сессия брошена посреди ввода текста). Лучше дать
        дописать. На процесс они не влияют: потоки daemon.
        """
        with self._lock:
            self._stopped = True
            live = len(self._live)
            abandoned = self._abandoned

        if live:
            logger.info(
                "РАННЕР ОСТАНОВЛЕН | живых=%d | покинутых=%d",
                live,
                abandoned,
            )
        return live

    # ------------------------------------------------------------------
    # Внутреннее
    # ------------------------------------------------------------------
    def _run(self, handle: Handle, fn: Callable[[], Any]) -> None:
        """Обёртка потока: гарантированно снимает поток с учёта."""
        try:
            handle.value = fn()
        except BaseException as exc:  # noqa: BLE001 - см. docstring
            # BaseException, а не Exception: `Cancelled` и прочие
            # управляющие исключения исполнителя тоже должны попасть
            # в хендл, а не в stderr. Исключение, прерывающее
            # интерпретатор (KeyboardInterrupt, SystemExit), —
            # в том числе, чтобы finally ниже отработал.
            handle.error = exc
            logger.debug("ШАГ УПАЛ | %s | %s", handle.name, type(exc).__name__)
        finally:
            # Порядок обязателен. `_done` ставится последним, иначе
            # вызывающий увидит сигнал о завершении раньше, чем
            # появятся value/error, и прочитает пустое.
            self._release(handle)
            handle.finished = True
            handle._done.set()

    def _release(self, handle: Handle) -> None:
        """Убирает поток из учёта. Идемпотентно."""
        with self._lock:
            self._live.pop(handle, None)
            if handle.abandoned and self._abandoned > 0:
                self._abandoned -= 1

    def _is_live(self, handle: Handle) -> bool:
        """Жив ли поток хендла.

        Только под локом и только как «есть в учёте и ещё не
        завершился». `is_alive()` без синхронизации читает состояние
        гонкой: поток мог и завершиться, и быть уже убран.
        """
        thread = self._live.get(handle)
        return thread is not None and thread.is_alive()